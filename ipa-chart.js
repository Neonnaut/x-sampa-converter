function x2i(input) {
    let out = "";
    let i = 0;

    while (i < input.length) {
        let matched = false;

        for (const [tok, ipa] of xti_entries) {
            if (input.startsWith(tok, i)) {
                out += ipa;
                i += tok.length;
                matched = true;
                break;
            }
        }

        if (!matched) {
            out += input[i];
            i++;
        }
    }

    return out;
}

