window.addEventListener('load', function () {
    // Keyup listeners for IPA and SAMPA boxes
    document.getElementById('ipa-box').addEventListener('keyup', translateIPA);
    document.getElementById('sampa-box').addEventListener('keyup', translateSAMPA);

    // Copy and clear buttons
    document.getElementById('copy-button').addEventListener('click', copyClip);
    document.getElementById('clear-button').addEventListener('click', clearFields);
});

function copyClip() {
    let copyText = parent.frames[1].document.getElementById("ipa-box");
    if (!navigator.clipboard) {
        // Select text for depreciated way.
        copyText.select();
        copyText.setSelectionRange(0, 99999); /*For mobile devices*/
        document.execCommand("copy"); // depreciated?
        document.getElementById("ipa-box").focus();
    } else {
        navigator.clipboard.writeText(copyText.value);
    }
}

function clearFields() {
    let e = document.getElementById("ipa-box").value;
    if (e == "") {
        return;
    } else {
        if (window.confirm("Clear all fields?")) {
            document.getElementById("sampa-box").value = "";
            document.getElementById("ipa-box").value = "";
        }
    }
}

function translateSAMPA() {
    var s = document.getElementById("sampa-box").value;
    document.getElementById("ipa-box").value = x2i(s);
}

function translateIPA() {
    var s = document.getElementById("ipa-box").value;
    document.getElementById("sampa-box").value = i2x(s);
}

